
;; # Перенос паров сурьмы в потоке водорода
;;
;; ## 1. Постановка задачи
;;
;;
;;
;; Рассматривается перенос паров сурьмы из нагретой исходной
;; ампулы в приёмную через соединительную цилиндрическую
;; трубку. Через систему непрерывно пропускается водород.
;; Приёмная ампула соединена с вакуумным насосом через
;; ловушку.
;;
;; ### 1.1. Допущения модели
;;
;; 1. **Стационарность.** Температуры, давления и молярные
;;    потоки не изменяются со временем.
;;
;; 2. **Одномерность.** Перенос рассматривается вдоль
;;    оси прямой цилиндрической трубки длиной $L$
;;    и внутренним диаметром $d$. Все величины,
;;    описывающие перенос, усредняются по сечению.
;;
;; 3. **Изотермичность.** Температура трубки постоянна
;;    по всей длине и равна температуре исходной
;;    ампулы $T_s$.
;;
;; 4. **Бинарная смесь.** Газовая фаза состоит из
;;    молекулярного водорода $\mathrm{H}_2$ и паров
;;    сурьмы, представленных молекулами $\mathrm{Sb}_4$.
;;    Другие молекулярные формы сурьмы не учитываются.
;;
;;
;; 5. **Идеальный газ.** Газовая смесь подчиняется
;;    уравнению состояния идеального газа.
;;
;; 6. **Равновесие на входе.** Испарение сурьмы
;;    в исходной ампуле обеспечивает насыщение пара
;;    у входа в трубку. Испарение не ограничивает
;;    скорость переноса.
;;
;; 7. **Идеальный поглотитель на выходе.** Приёмная
;;    ампула полностью поглощает поступающие пары
;;    сурьмы. Их парциальное давление на выходе
;;    трубки принимается равным нулю.
;;
;; 8. **Отсутствие осаждения в трубке.** Сурьма
;;    не конденсируется на внутренних стенках.
;;    Молярные расходы обоих компонентов сохраняются
;;    вдоль трубки.
;;
;; 9. **Отсутствие химических реакций.** Компоненты
;;    не взаимодействуют химически между собой
;;    и с материалом трубки.
;;
;; 10. **Постоянный расход водорода.** Молярный расход
;;     водорода задаётся внешним регулятором и не
;;     зависит от условий в соединительной трубке.
;;
;; 11. **Ловушка.** Сопротивление ловушки описывается
;;     постоянной эффективной газовой проводимостью.
;;     Дополнительные сопротивления газовых линий
;;     не учитываются.
;;
;; ### 1.2. Обозначения
;;
;; Введём осевую координату $z$, направленную от
;; исходной ампулы к приёмной:
;;
;; $$
;; 0\le z\le L,\qquad S=\frac{\pi d^2}{4}.
;; $$
;;
;; Обозначим компоненты смеси индексами:
;;
;; $$
;; A=\mathrm{Sb}_4,\qquad B=\mathrm{H}_2.
;; $$
;;
;; Парциальные давления компонентов $p_A$, $p_B$
;; связаны с полным давлением $p$ соотношениями:
;;
;; $$
;; p=p_A+p_B,\qquad
;; x_A=\frac{p_A}{p},\qquad
;; x_B=\frac{p_B}{p}.
;; $$
;;
;; Молярные потоки $N_A$ и $N_B$ определяются
;; относительно неподвижной трубки и считаются
;; положительными в направлении возрастания $z$.
;;
;; ## 2. Граничные условия
;;
;; ### 2.1. Вход в трубку
;;
;; На входе $z=0$ парциальное давление сурьмы
;; принимается равным давлению насыщенного пара
;; при температуре исходной ампулы $T_s$:
;;
;; $$
;; \boxed{p_A(0)=p_{A,\mathrm{sat}}(T_s).}
;; $$
;;
;; В рамках бинарного приближения давление
;; насыщенного пара приписывается компоненту
;; $\mathrm{Sb}_4$.
;;
;; Полное давление на входе заранее неизвестно:
;;
;; $$
;; p(0)=p_A(0)+p_B(0).
;; $$
;;
;; ### 2.2. Выход из трубки
;;
;; На выходе $z=L$ приёмная ампула рассматривается
;; как идеальный поглотитель паров сурьмы:
;;
;; $$
;; \boxed{p_A(L)=0.}
;; $$
;;
;; Следовательно, полное давление на выходе
;; определяется только водородом:
;;
;; $$
;; p(L)=p_B(L).
;; $$
;;
;; Манометр находится после ловушки, со стороны
;; вакуумного насоса. Обозначим его показание $p_g$.
;;
;; В приближении постоянной эффективной
;; проводимости ловушки:
;;
;; $$
;; \boxed{
;; p_B(L)=p_g+\frac{Q_B}{C_{\mathrm{trap}}}.
;; }
;; $$
;;
;;
;;
;; Здесь $Q_B$ — газовый поток водорода в единицах
;; давления, умноженного на объём за единицу времени,
;; а $C_{\mathrm{trap}}$ — эффективная проводимость
;; ловушки. Обе величины относятся к одной
;; температурной конвенции.
;;
;; ### 2.3. Расход водорода
;;
;;
;; Регулятор задаёт объёмный расход водорода
;; $\dot V_{\mathrm{ref}}$, приведённый к опорным
;; давлению $p_{\mathrm{ref}}$ и температуре
;; $T_{\mathrm{ref}}$.
;;
;; Соответствующий молярный расход составляет:
;;
;;
;; $$
;; \boxed{
;; \overset{\cdot}{n}_B=
;; \frac{p_{\mathrm{ref}}\overset{\bullet}{V}_{\mathrm{ref}}}
;; {RT_{\mathrm{ref}}}.
;; }
;; $$
;;
;;
;; В отсутствие источников и стоков водорода:
;;
;; $$
;; \overset{\bullet}{n}_B=N_B S=\mathrm{const}.
;; $$
;;
;; Молярный расход сурьмы также сохраняется
;; вдоль трубки, но заранее неизвестен:
;;
;; $$
;; \overset{\bullet}{n}_A=N_A S=\mathrm{const}.
;; $$
;;
;; Определение $\dot n_A$ является основной задачей
;; дальнейшего расчёта.
