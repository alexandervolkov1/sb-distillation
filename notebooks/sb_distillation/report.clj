;; # Перенос паров сурьмы в потоке водорода
;;
;; ## 1. Постановка задачи
;;
;; Рассматривается перенос паров сурьмы из нагретой исходной
;; ампулы в приёмную через соединительную цилиндрическую
;; трубку. Через систему непрерывно пропускается водород.
;; Приёмная ампула соединена с вакуумным насосом через
;; ловушку.
;;
;; ### 1.1. Допущения модели
;;
;; 1. **Стационарность.** Температуры, давления и молярные
;;    потоки не изменяются со временем.
;;
;; 2. **Одномерность.** Перенос рассматривается вдоль
;;    оси прямой цилиндрической трубки длиной $L$
;;    и внутренним диаметром $d$. Все величины,
;;    описывающие перенос, усредняются по сечению.
;;
;; 3. **Изотермичность.** Температура трубки постоянна
;;    по всей длине и равна температуре исходной
;;    ампулы $T_s$.
;;
;; 4. **Бинарная смесь.** Газовая фаза состоит из
;;    молекулярного водорода $\mathrm{H}_2$ и паров
;;    сурьмы, представленных молекулами $\mathrm{Sb}_4$.
;;    Другие молекулярные формы сурьмы не учитываются.
;;
;; 5. **Идеальный газ.** Газовая смесь подчиняется
;;    уравнению состояния идеального газа.
;;
;; 6. **Равновесие на входе.** Испарение сурьмы
;;    в исходной ампуле обеспечивает насыщение пара
;;    у входа в трубку. Испарение не ограничивает
;;    скорость переноса.
;;
;; 7. **Идеальный поглотитель на выходе.** Приёмная
;;    ампула полностью поглощает поступающие пары
;;    сурьмы. Их парциальное давление на выходе
;;    трубки принимается равным нулю.
;;
;; 8. **Отсутствие осаждения в трубке.** Сурьма
;;    не конденсируется на внутренних стенках.
;;    Молярные расходы обоих компонентов сохраняются
;;    вдоль трубки.
;;
;; 9. **Отсутствие химических реакций.** Компоненты
;;    не взаимодействуют химически между собой
;;    и с материалом трубки.
;;
;; 10. **Постоянный расход водорода.** Молярный расход
;;     водорода задаётся внешним регулятором и не
;;     зависит от условий в соединительной трубке.
;;
;; 11. **Ловушка.** Сопротивление ловушки описывается
;;     постоянной эффективной газовой проводимостью.
;;     Дополнительные сопротивления газовых линий
;;     не учитываются.
;;
;; ## 2. Математическая модель переноса газовой смеси
;;
;; Для описания переноса паров сурьмы в потоке водорода
;; используется модель цилиндрического капилляра с
;; интерполяцией между предельными режимами течения
;; (Cylindrical Pore Interpolation Model, CPIM),
;; предложенная Young и Todd (2005).
;;
;; Модель объединяет описание многокомпонентного вязкого
;; течения в континуальном режиме с молекулярным
;; переносом в режиме Кнудсена. Промежуточный режим
;; описывается интерполяцией между этими пределами.
;;
;; ### 2.1. Граничные условия и искомые величины
;;
;; Рассматривается перенос бинарной газовой смеси
;; через цилиндрическую трубку длиной $L$ и внутренним
;; диаметром $d$. Компоненты смеси обозначаются индексами
;;
;; $$
;; 1=\mathrm{Sb}_4,\qquad 2=\mathrm{H}_2.
;; $$
;;
;; Ось $z$ направлена от исходной ампулы к приёмной:
;;
;; $$
;; 0\le z\le L,\qquad S=\frac{\pi d^2}{4}.
;; $$
;;
;; Парциальные давления компонентов $p_1(z)$ и $p_2(z)$
;; связаны с полным давлением соотношением
;;
;; $$
;; p(z)=p_1(z)+p_2(z).
;; $$
;;
;; Молярные потоки $N_1$ и $N_2$ определяются
;; относительно неподвижной трубки и считаются
;; положительными в направлении возрастания $z$.
;; В стационарном режиме они постоянны по длине трубки.
;;
;; **Вход в трубку ($z=0$).**
;;
;; Парциальное давление сурьмы определяется равновесием
;; с жидкой сурьмой при температуре исходной ампулы $T_s$:
;;
;; $$
;; \boxed{p_1(0)=p_{1,\mathrm{sat}}(T_s).}
;; $$
;;
;; Парциальное давление водорода $p_2(0)$, как и полное
;; давление на входе, заранее неизвестно.
;;
;; **Выход из трубки ($z=L$).**
;;
;; Приёмная ампула рассматривается как идеальный
;; поглотитель паров сурьмы:
;;
;; $$
;; \boxed{p_1(L)=0.}
;; $$
;;
;; Давление водорода определяется показанием вакуумметра,
;; установленного после ловушки, и её эффективной
;; проводимостью:
;;
;; $$
;; \boxed{
;; p_2(L)=p_g+\frac{Q_2}{C_{\mathrm{trap}}}.
;; }
;; $$
;;
;; Здесь $p_g$ является давлением водорода со стороны
;; насоса, $Q_2$ представляет газовый поток водорода,
;; а $C_{\mathrm{trap}}$ обозначает эффективную
;; проводимость ловушки для водорода.
;;
;; Если объёмный расход $\overset{\cdot}{V}_{\mathrm{ref}}$
;; задан при опорных давлении $p_{\mathrm{ref}}$
;; и температуре $T_{\mathrm{ref}}$, то
;;
;; $$
;; Q_2=p_{\mathrm{ref}}
;; \overset{\cdot}{V}_{\mathrm{ref}}.
;; $$
;;
;; При этом проводимость ловушки должна быть определена
;; с использованием той же конвенции для газового потока.
;;
;; **Расход водорода.**
;;
;; Молярный расход водорода задаётся регулятором:
;;
;; $$
;; \overset{\cdot}{n}_2=
;; \frac{p_{\mathrm{ref}}
;; \overset{\cdot}{V}_{\mathrm{ref}}}
;; {RT_{\mathrm{ref}}}.
;; $$
;;
;; Соответствующий молярный поток через поперечное
;; сечение трубки составляет
;;
;; $$
;; \boxed{
;; N_2=
;; \frac{p_{\mathrm{ref}}
;; \overset{\cdot}{V}_{\mathrm{ref}}}
;; {RT_{\mathrm{ref}}S}.
;; }
;; $$
;;
;; Таким образом, заданы молярный поток водорода $N_2$
;; и три граничных условия:
;;
;; $$
;; \boxed{
;; \begin{aligned}
;; p_1(0)&=p_{1,\mathrm{sat}}(T_s),\\
;; p_1(L)&=0,\\
;; p_2(L)&=p_g+\frac{Q_2}{C_{\mathrm{trap}}}.
;; \end{aligned}
;; }
;; $$
;;
;; **Основной неизвестной величиной является молярный
;; поток сурьмы $N_1$.** Одновременно должны быть
;; определены распределения парциальных давлений
;; $p_1(z)$ и $p_2(z)$.
;;
;; Для нахождения этих величин необходимо установить
;; связь между молярными потоками и градиентами давления
;; и состава газовой смеси. Такая связь будет получена
;; из уравнений CPIM.
