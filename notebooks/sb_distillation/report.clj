;; ## 2. Численная постановка задачи
;;
;; Для расчёта переноса бинарной смеси Sb₄–H₂ используется
;; изотермическая модель запылённого газа
;; (Dusty Gas Model, DGM), учитывающая межмолекулярную
;; диффузию, столкновения молекул со стенками
;; и вязкое течение.
;;
;; Используется координата $z$, направленная
;; от исходной ампулы ($z=0$) к приёмной ($z=L$).
;; Молярные потоки положительны в том же направлении.
;;
;; ### 2.1. Система дифференциальных уравнений
;;
;; Введём вспомогательные величины:
;;
;; $$
;; \begin{aligned}
;; p = p_A+p_B,\\
;; x_i = \frac{p_i}{p},\\
;; K_{AB} = pD_{AB},\\
;; \alpha_i = \frac{B_0p_i}{\mu D_{K,i}},\\
;; G = -\frac{RT}{1+\alpha_A+\alpha_B}
;; \left(
;; \frac{N_A}{D_{K,A}}+
;; \frac{N_B}{D_{K,B}}
;; \right).
;; \end{aligned}
;; $$
;;
;; Здесь $G=dp/dz$.
;;
;; Система для парциальных давлений имеет вид:
;;
;; $$
;; \boxed{
;; \begin{aligned}
;; \frac{dp_A}{dz}
;; &=-RT\left[
;; \frac{N_A}{D_{K,A}}+
;; \frac{p_BN_A-p_AN_B}{K_{AB}}
;; \right]-\alpha_A G,
;; \\[8pt]
;; \frac{dp_B}{dz}
;; &=-RT\left[
;; \frac{N_B}{D_{K,B}}-
;; \frac{p_BN_A-p_AN_B}{K_{AB}}
;; \right]-\alpha_B G.
;; \end{aligned}
;; }
;; $$
;;
;; При стационарном переносе без источников
;; и стоков компонентов:
;;
;; $$
;; \frac{dN_A}{dz}=
;; \frac{dN_B}{dz}=0,
;; \qquad T=T_s.
;; $$
;;
;; ### 2.2. Транспортные коэффициенты
;;
;; Для прямой цилиндрической трубки в приближении
;; диффузного отражения молекул от стенок:
;;
;; $$
;; D_{K,i}=\frac{d}{3}
;; \sqrt{\frac{8RT}{\pi M_i}},
;; \qquad
;; B_0=\frac{d^2}{32}.
;; $$
;;
;; Коэффициент взаимной диффузии рассчитывается
;; в приближении твёрдых сфер:
;;
;; $$
;; K_{AB}=
;; \frac{3k_BT}{16\sigma_{AB}^{2}}
;; \sqrt{\frac{2k_BT}{\pi m_{\mathrm{red}}}}.
;; $$
;;
;; При этом:
;;
;; $$
;; \begin{aligned}
;; \sigma_{AB}&=\frac{\sigma_A+\sigma_B}{2},\\
;; m_{\mathrm{red}}&=\frac{m_Am_B}{m_A+m_B},\\
;; m_i&=\frac{M_i}{N_{\mathrm{Av}}}.
;; \end{aligned}
;; $$
;;
;; Вязкость смеси определяется по правилу Уилки:
;;
;; $$
;; \mu=
;; \sum_{i=A,B}
;; \frac{x_i\mu_i}
;; {\displaystyle\sum_{j=A,B}x_j\Phi_{ij}},
;; $$
;;
;; где
;;
;; $$
;; \Phi_{ij}=
;; \frac{
;; \left[
;; 1+\sqrt{\frac{\mu_i}{\mu_j}}
;; \left(\frac{M_j}{M_i}\right)^{1/4}
;; \right]^2
;; }{
;; \sqrt{8\left(1+\frac{M_i}{M_j}\right)}
;; }.
;; $$
;;
;; Вязкость Sb₄ рассчитывается в приближении
;; твёрдых сфер:
;;
;; $$
;; \mu_A=
;; \frac{5}{16\sigma_A^2}
;; \sqrt{\frac{m_Ak_BT}{\pi}}.
;; $$
;;
;; Вязкость водорода рассчитывается по формуле
;; Сазерленда:
;;
;; $$
;; \mu_B(T)=\mu_{B,0}
;; \left(\frac{T}{T_{B,0}}\right)^{3/2}
;; \frac{T_{B,0}+S_B}{T+S_B}.
;; $$
;;
;; ## 3. Граничные условия
;;
;; ### 3.1. Выход из трубки ($z=L$)
;;
;; Приёмная ампула считается идеальным
;; поглотителем паров сурьмы:
;;
;; $$
;; \boxed{p_A(L)=0.}
;; $$
;;
;; Давление водорода определяется сопротивлением
;; ловушки и показанием манометра:
;;
;; $$
;; \boxed{
;; p_B(L)=p_g+\frac{Q_B}{C_{\mathrm{trap}}}.
;; }
;; $$
;;
;; Газовый поток водорода при опорных условиях:
;;
;; $$
;; Q_B=p_{\mathrm{ref}}
;; \overset{\bullet}{V}_{\mathrm{ref}}.
;; $$
;;
;; Газовый поток и проводимость ловушки определены
;; в согласованных опорных условиях.
;;
;; ### 3.2. Заданный расход водорода
;;
;; Молярный расход водорода задаётся регулятором:
;;
;; $$
;; \boxed{
;; \overset{\bullet}{n}_B=
;; \frac{
;; p_{\mathrm{ref}}
;; \overset{\bullet}{V}_{\mathrm{ref}}
;; }{RT_{\mathrm{ref}}}.
;; }
;; $$
;;
;; Молярный поток через сечение трубки:
;;
;; $$
;; \boxed{
;; N_B=
;; \frac{
;; p_{\mathrm{ref}}
;; \overset{\bullet}{V}_{\mathrm{ref}}
;; }{RT_{\mathrm{ref}}S}.
;; }
;; $$
;;
;; ### 3.3. Вход в трубку ($z=0$)
;;
;; Пар сурьмы считается насыщенным.
;; Скорость испарения из расплава не ограничивает
;; скорость переноса:
;;
;; $$
;; \boxed{
;; p_A(0)=p_{A,\mathrm{sat}}(T_s).
;; }
;; $$
;;
;; В рамках бинарного приближения давление
;; насыщенного пара приписывается компоненту Sb₄.
;; Полное давление на входе заранее неизвестно.
;;
;; ## 4. Определение расхода сурьмы
;;
;; Молярный поток сурьмы $N_A$ определяется
;; подбором такого значения, при котором решение
;; системы дифференциальных уравнений удовлетворяет
;; граничному условию на входе.
;;
;; Интегрирование ведётся от $z=L$ к $z=0$,
;; то есть с отрицательным шагом по координате $z$.
;; Начальными значениями служат $p_A(L)$ и $p_B(L)$.
;;
;; Невязка определяется выражением:
;;
;; $$
;; \boxed{
;; F(N_A)=p_A(0;N_A)-
;; p_{A,\mathrm{sat}}(T_s).
;; }
;; $$
;;
;; Требуется найти неотрицательный корень:
;;
;; $$
;; F(N_A)=0,\qquad N_A\ge 0.
;; $$
;;
;; После определения $N_A$ молярный
;; и массовый расходы сурьмы составляют:
;;
;; $$
;; \boxed{
;; \begin{aligned}
;; \overset{\bullet}{n}_A&=N_AS,\\
;; \overset{\bullet}{m}_A&=M_AN_AS.
;; \end{aligned}
;; }
;; $$
;;
;; При интегрировании контролируются неотрицательность
;; парциальных давлений и устойчивость результата
;; при уменьшении шага. Численное значение
;; $p_{A,\mathrm{sat}}(T_s)$ определяется отдельно
;; по принятой корреляции давления пара.
;;
;; ## 5. Источники
;;
