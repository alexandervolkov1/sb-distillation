;; # Перенос паров сурьмы в потоке водорода
;;
;; ## 1. Постановка задачи
;;
;; Рассматривается перенос паров сурьмы из нагретой исходной
;; ампулы в приёмную через соединительную цилиндрическую
;; трубку. Через систему непрерывно пропускается водород.
;; Приёмная ампула соединена с вакуумным насосом через
;; ловушку.
;;
;; ### 1.1. Допущения модели
;;
;; 1. **Стационарность.** Температуры, давления и молярные
;;    потоки не изменяются со временем.
;;
;; 2. **Одномерность.** Перенос рассматривается вдоль
;;    оси прямой цилиндрической трубки длиной $L$
;;    и внутренним диаметром $d$. Все величины,
;;    описывающие перенос, усредняются по сечению.
;;
;; 3. **Изотермичность.** Температура трубки постоянна
;;    по всей длине и равна температуре исходной
;;    ампулы $T_s$.
;;
;; 4. **Бинарная смесь.** Газовая фаза состоит из
;;    молекулярного водорода $\mathrm{H}_2$ и паров
;;    сурьмы, представленных молекулами $\mathrm{Sb}_4$.
;;    Другие молекулярные формы сурьмы не учитываются.
;;
;; 5. **Идеальный газ.** Газовая смесь подчиняется
;;    уравнению состояния идеального газа.
;;
;; 6. **Равновесие на входе.** Испарение сурьмы
;;    в исходной ампуле обеспечивает насыщение пара
;;    у входа в трубку. Испарение не ограничивает
;;    скорость переноса.
;;
;; 7. **Идеальный поглотитель на выходе.** Приёмная
;;    ампула полностью поглощает поступающие пары
;;    сурьмы. Их парциальное давление на выходе
;;    трубки принимается равным нулю.
;;
;; 8. **Отсутствие осаждения в трубке.** Сурьма
;;    не конденсируется на внутренних стенках.
;;    Молярные расходы обоих компонентов сохраняются
;;    вдоль трубки.
;;
;; 9. **Отсутствие химических реакций.** Компоненты
;;    не взаимодействуют химически между собой
;;    и с материалом трубки.
;;
;; 10. **Постоянный расход водорода.** Молярный расход
;;     водорода задаётся внешним регулятором и не
;;     зависит от условий в соединительной трубке.
;;
;; 11. **Ловушка.** Сопротивление ловушки описывается
;;     постоянной эффективной газовой проводимостью.
;;     Дополнительные сопротивления газовых линий
;;     не учитываются.
;;
;; ### 1.2. Обозначения
;;
;; Все величины выражены в единицах СИ.
;;
;; ::: {.symbols-table}
;;
;; | Обозначение | Физическая величина | Единица СИ |
;; |:---|:---|:---:|
;; | $z$ | Координата от источника к приёмнику | м |
;; | $L$ | Длина трубки | м |
;; | $d$ | Внутренний диаметр трубки | м |
;; | $S$ | Площадь поперечного сечения | м² |
;; | $T$ | Температура газа в трубке | К |
;; | $T_s$ | Температура исходной ампулы | К |
;; | $T_r$ | Температура приёмной ампулы | К |
;; | $T_{\mathrm{ref}}$ | Опорная температура расхода | К |
;; | $T_{B,0}$ | Опорная температура вязкости H₂ | К |
;; | $S_B$ | Постоянная Сазерленда для H₂ | К |
;; | $p$ | Полное давление газовой смеси | Па |
;; | $p_i$ | Парциальное давление компонента $i$ | Па |
;; | $p_{A,\mathrm{sat}}$ | Давление насыщенного пара сурьмы | Па |
;; | $p_g$ | Давление после ловушки | Па |
;; | $p_{\mathrm{ref}}$ | Опорное давление расхода | Па |
;; | $x_i$ | Мольная доля компонента $i$ | 1 |
;; | $N_i$ | Молярный поток компонента $i$ | моль/(м²·с) |
;; | $\overset{\bullet}{n}_i$ | Молярный расход компонента $i$ | моль/с |
;; | $\overset{\bullet}{m}_A$ | Массовый расход сурьмы | кг/с |
;; | $\overset{\bullet}{V}_{\mathrm{ref}}$ | Объёмный расход H₂ при опорных условиях | м³/с |
;; | $Q_B$ | Газовый поток H₂ через ловушку | Па·м³/с |
;; | $C_{\mathrm{trap}}$ | Эффективная проводимость ловушки | м³/с |
;; | $D_{AB}$ | Коэффициент взаимной диффузии | м²/с |
;; | $D_{K,i}$ | Коэффициент кнудсеновской диффузии | м²/с |
;; | $K_{AB}$ | Произведение $pD_{AB}$ | Па·м²/с |
;; | $B_0$ | Коэффициент вязкой проницаемости | м² |
;; | $\mu$ | Динамическая вязкость смеси | Па·с |
;; | $\mu_i$ | Динамическая вязкость компонента $i$ | Па·с |
;; | $\mu_{B,0}$ | Опорная вязкость H₂ | Па·с |
;; | $\Phi_{ij}$ | Коэффициент взаимодействия Уилки | 1 |
;; | $M_i$ | Молярная масса компонента $i$ | кг/моль |
;; | $m_i$ | Масса одной молекулы компонента $i$ | кг |
;; | $m_{\mathrm{red}}$ | Приведённая масса пары молекул | кг |
;; | $\sigma_i$ | Эффективный диаметр молекулы | м |
;; | $\sigma_{AB}$ | Эффективный диаметр столкновения A–B | м |
;; | $\alpha_i$ | Безразмерный коэффициент вязкого вклада | 1 |
;; | $G$ | Градиент полного давления по $z$ | Па/м |
;; | $F(N_A)$ | Невязка граничного условия | Па |
;; | $R$ | Универсальная газовая постоянная | Дж/(моль·К) |
;; | $k_B$ | Постоянная Больцмана | Дж/К |
;; | $N_{\mathrm{Av}}$ | Постоянная Авогадро | моль⁻¹ |
;;
;; :::
;;
;; Индексами $A$ и $B$ обозначены компоненты смеси:
;;
;; $$
;; A=\mathrm{Sb}_4,\qquad B=\mathrm{H}_2.
;; $$
;;
;; Ось $z$ направлена от исходной ампулы к приёмной:
;;
;; $$
;; 0 ⩽ z ⩽ L,\qquad
;; S=\frac{\pi d^2}{4}.
;; $$
;;
;; Молярные потоки $N_A$ и $N_B$ определяются
;; относительно неподвижной трубки и считаются
;; положительными в направлении возрастания $z$.
;;
;; ### 1.3. Схема установки
;;
;; Схематическое изображение установки и расчётной
;; области переноса газовой смеси.

