;; # Перенос паров сурьмы в потоке водорода
;;
;; ## 1. Постановка задачи
;;
;; Рассматривается перенос паров сурьмы из нагретой исходной
;; ампулы в приёмную через соединительную цилиндрическую
;; трубку. Через систему непрерывно пропускается водород.
;; Приёмная ампула соединена с вакуумным насосом через
;; ловушку.
;;
;; ### 1.1. Допущения модели
;;
;; 1. **Стационарность.** Температуры, давления и молярные
;;    потоки не изменяются со временем.
;;
;; 2. **Одномерность.** Перенос рассматривается вдоль
;;    оси прямой цилиндрической трубки длиной $L$
;;    и внутренним диаметром $d$. Все величины,
;;    описывающие перенос, усредняются по сечению.
;;
;; 3. **Изотермичность.** Температура трубки постоянна
;;    по всей длине и равна температуре исходной
;;    ампулы $T_s$.
;;
;; 4. **Бинарная смесь.** Газовая фаза состоит из
;;    молекулярного водорода $\mathrm{H}_2$ и паров
;;    сурьмы, представленных молекулами $\mathrm{Sb}_4$.
;;    Другие молекулярные формы сурьмы не учитываются.
;;
;; 5. **Идеальный газ.** Газовая смесь подчиняется
;;    уравнению состояния идеального газа.
;;
;; 6. **Равновесие на входе.** Испарение сурьмы
;;    в исходной ампуле обеспечивает насыщение пара
;;    у входа в трубку. Испарение не ограничивает
;;    скорость переноса.
;;
;; 7. **Идеальный поглотитель на выходе.** Приёмная
;;    ампула полностью поглощает поступающие пары
;;    сурьмы. Их парциальное давление на выходе
;;    трубки принимается равным нулю.
;;
;; 8. **Отсутствие осаждения в трубке.** Сурьма
;;    не конденсируется на внутренних стенках.
;;    Молярные расходы обоих компонентов сохраняются
;;    вдоль трубки.
;;
;; 9. **Отсутствие химических реакций.** Компоненты
;;    не взаимодействуют химически между собой
;;    и с материалом трубки.
;;
;; 10. **Постоянный расход водорода.** Молярный расход
;;     водорода задаётся внешним регулятором и не
;;     зависит от условий в соединительной трубке.
;;
;; 11. **Ловушка.** Сопротивление ловушки описывается
;;     постоянной эффективной газовой проводимостью.
;;     Дополнительные сопротивления газовых линий
;;     не учитываются.
;;
;; ## 2. Математическая модель переноса газовой смеси
;;
;; Для описания переноса паров сурьмы в потоке водорода
;; используется модель цилиндрического капилляра с
;; интерполяцией между предельными режимами течения
;; (Cylindrical Pore Interpolation Model, CPIM),
;; предложенная Young и Todd (2005).
;;
;; Модель объединяет описание многокомпонентного вязкого
;; течения в континуальном режиме с молекулярным
;; переносом в режиме Кнудсена. Промежуточный режим
;; описывается интерполяцией между этими пределами.
;;
;; ### 2.1. Граничные условия и искомые величины
;;
;; Рассматривается перенос бинарной газовой смеси
;; через цилиндрическую трубку длиной $L$ и внутренним
;; диаметром $d$. Компоненты смеси обозначаются индексами
;;
;; $$
;; 1=\mathrm{Sb}_4,\qquad 2=\mathrm{H}_2.
;; $$
;;
;; Ось $z$ направлена от исходной ампулы к приёмной:
;;
;; $$
;; 0⩽ z⩽ L,\qquad S=\frac{\pi d^2}{4}.
;; $$
;;
;; Парциальные давления компонентов $p_1(z)$ и $p_2(z)$
;; связаны с полным давлением соотношением
;;
;; $$
;; p(z)=p_1(z)+p_2(z).
;; $$
;;
;; Молярные потоки $N_1$ и $N_2$ определяются
;; относительно неподвижной трубки и считаются
;; положительными в направлении возрастания $z$.
;; В стационарном режиме они постоянны по длине трубки.
;;
;; **Вход в трубку ($z=0$).**
;;
;; Парциальное давление сурьмы определяется равновесием
;; с жидкой сурьмой при температуре исходной ампулы $T_s$:
;;
;; $$
;; \boxed{p_1(0)=p_{1,\mathrm{sat}}(T_s).}
;; $$
;;
;; Парциальное давление водорода $p_2(0)$, как и полное
;; давление на входе, заранее неизвестно.
;;
;; **Выход из трубки ($z=L$).**
;;
;; Приёмная ампула рассматривается как идеальный
;; поглотитель паров сурьмы:
;;
;; $$
;; \boxed{p_1(L)=0.}
;; $$
;;
;; Давление водорода определяется показанием вакуумметра,
;; установленного после ловушки, и её эффективной
;; проводимостью:
;;
;; $$
;; \boxed{
;; p_2(L)=p_g+\frac{Q_2}{C_{\mathrm{trap}}}.
;; }
;; $$
;;
;; Здесь $p_g$ является давлением водорода со стороны
;; насоса, $Q_2$ представляет газовый поток водорода,
;; а $C_{\mathrm{trap}}$ обозначает эффективную
;; проводимость ловушки для водорода.
;;
;; Если объёмный расход $\overset{\cdot}{V}_{\mathrm{ref}}$
;; задан при опорных давлении $p_{\mathrm{ref}}$
;; и температуре $T_{\mathrm{ref}}$, то
;;
;; $$
;; Q_2=p_{\mathrm{ref}}
;; \overset{\cdot}{V}_{\mathrm{ref}}.
;; $$
;;
;; При этом проводимость ловушки должна быть определена
;; с использованием той же конвенции для газового потока.
;;
;; **Расход водорода.**
;;
;; Молярный расход водорода задаётся регулятором:
;;
;; $$
;; \overset{\cdot}{n}_2=
;; \frac{p_{\mathrm{ref}}
;; \overset{\cdot}{V}_{\mathrm{ref}}}
;; {RT_{\mathrm{ref}}}.
;; $$
;;
;; Соответствующий молярный поток через поперечное
;; сечение трубки составляет
;;
;; $$
;; \boxed{
;; N_2=
;; \frac{p_{\mathrm{ref}}
;; \overset{\cdot}{V}_{\mathrm{ref}}}
;; {RT_{\mathrm{ref}}S}.
;; }
;; $$
;;
;; Таким образом, заданы молярный поток водорода $N_2$
;; и три граничных условия:
;;
;; $$
;; \boxed{
;; \begin{aligned}
;; p_1(0)&=p_{1,\mathrm{sat}}(T_s),\\
;; p_1(L)&=0,\\
;; p_2(L)&=p_g+\frac{Q_2}{C_{\mathrm{trap}}}.
;; \end{aligned}
;; }
;; $$
;;
;; **Основной неизвестной величиной является молярный
;; поток сурьмы $N_1$.** Одновременно должны быть
;; определены распределения парциальных давлений
;; $p_1(z)$ и $p_2(z)$.
;;
;; Для нахождения этих величин необходимо установить
;; связь между молярными потоками и градиентами давления
;; и состава газовой смеси. Такая связь будет получена
;; из уравнений CPIM.

;;
;; ### 2.2. Континуальный режим переноса
;;
;; Рассмотрим предел малого числа Кнудсена,
;; когда длина свободного пробега молекул
;; значительно меньше диаметра трубки:
;;
;; $$
;; Kn=\frac{\lambda}{d}\ll 1.
;; $$
;;
;; В этом режиме преобладают межмолекулярные
;; столкновения. Перенос компонентов описывается
;; уравнениями Максвелла — Стефана, а движение
;; газовой смеси под действием градиента давления
;; подчиняется уравнениям вязкого течения.
;;
;; #### 2.2.1. Взаимная диффузия компонентов
;;
;; Введём суммарную молярную концентрацию $c$
;; и мольные доли компонентов $x_i$:
;;
;; $$
;; c=\frac{p}{RT},\qquad
;; x_i=\frac{p_i}{p},\qquad x_1+x_2=1.
;; $$
;;
;; Полный молярный поток каждого компонента
;; можно представить как сумму конвективной
;; и диффузионной составляющих:
;;
;; $$
;; N_i=x_iN+J_{\mathrm{diff},i},
;; \qquad N=N_1+N_2.
;; $$
;;
;; Здесь $N_i$ обозначает поток, усреднённый
;; по поперечному сечению трубки, а
;; $J_{\mathrm{diff},i}$ — диффузионную составляющую
;; относительно молярно-усреднённого движения смеси.
;;
;; Для бинарной смеси:
;;
;; $$
;; J_{\mathrm{diff},1}
;; +J_{\mathrm{diff},2}=0.
;; $$
;;
;; Уравнение Максвелла — Стефана связывает
;; градиент состава с относительным движением
;; компонентов:
;;
;; $$
;; \boxed{
;; c\frac{dx_1}{dz}
;; =\frac{x_1N_2-x_2N_1}{D_{12}}.
;; }
;; $$
;;
;; Коэффициент $D_{12}$ характеризует взаимную
;; диффузию компонентов вследствие межмолекулярных
;; столкновений.
;;
;; В CPIM принимается, что диффузионные потоки
;; не зависят от радиальной координаты. При этом
;; полные потоки компонентов могут изменяться
;; по сечению из-за вязкого движения смеси.
;;
;; #### 2.2.2. Диффузионное скольжение
;;
;; В однокомпонентном газе при континуальном
;; течении обычно принимается нулевая скорость
;; газа непосредственно у неподвижной стенки.
;;
;; Для многокомпонентной смеси с градиентом
;; состава это условие в общем случае неверно.
;; Молекулы разных компонентов переносят к стенке
;; неодинаковый тангенциальный импульс.
;;
;; В результате даже при отсутствии градиента
;; полного давления возможно ненулевое движение
;; смеси вблизи стенки. Этот эффект называется
;; диффузионным скольжением (diffusion slip).
;;
;; В модели Young и Todd предполагается, что
;; коэффициенты диффузного отражения молекул
;; от стенки одинаковы для всех компонентов.
;;
;; Из баланса тангенциального импульса получается
;; условие для суммарного молярного потока
;; смеси у стенки:
;;
;; $$
;; \boxed{
;; N_w=
;; -\frac{
;; \sqrt{M_1}J_{\mathrm{diff},1}
;; +\sqrt{M_2}J_{\mathrm{diff},2}
;; }{
;; x_1\sqrt{M_1}+x_2\sqrt{M_2}
;; }.
;; }
;; $$
;;
;; Здесь $N_w$ — суммарный молярный поток у стенки,
;; а $M_1$ и $M_2$ — молярные массы компонентов.
;;
;; Таким образом, диффузионное скольжение зависит
;; от диффузионных потоков и молярных масс газов.
;; При одинаковых молярных массах компонентов
;; данный вклад обращается в нуль.
;;
;; Диффузионное скольжение следует отличать
;; от вязкого скольжения, возникающего при
;; увеличении длины свободного пробега.
;; В рассматриваемом континуальном пределе
;; вязким скольжением пренебрегаем.
;;
;; #### 2.2.3. Вязкое движение газовой смеси
;;
;; Обозначим радиус трубки через $a=d/2$,
;; а радиальную координату через $r$.
;;
;; Для установившегося ламинарного течения
;; массовый поток смеси имеет профиль
;;
;; $$
;; g(r)=g_w-
;; \frac{\rho}{4\mu}(a^2-r^2)
;; \frac{dp}{dz},
;; $$
;;
;; где $g_w$ — массовый поток у стенки,
;; $\rho$ — плотность смеси, а $\mu$ —
;; её динамическая вязкость.
;;
;; Усреднение по поперечному сечению даёт:
;;
;; $$
;; \overline g=g_w-
;; \frac{\rho a^2}{8\mu}\frac{dp}{dz}.
;; $$
;;
;; В отличие от обычного закона Пуазейля,
;; здесь величина $g_w$ не полагается равной нулю,
;; а определяется диффузионным скольжением.
;;
;; Полный массовый поток равен
;;
;; $$
;; \overline g=M_1N_1+M_2N_2.
;; $$
;;
;; Подставляя условие диффузионного скольжения
;; в выражение для среднего массового потока,
;; получаем уравнение градиента полного давления:
;;
;; $$
;; \boxed{
;; \frac{dp}{dz}
;; =-\frac{32\mu RT}{pd^2}
;; \frac{
;; \sqrt{M_1}N_1+\sqrt{M_2}N_2
;; }{
;; x_1\sqrt{M_1}+x_2\sqrt{M_2}
;; }.
;; }
;; $$
;;
;; Это уравнение описывает изменение полного
;; давления при совместном вязком и диффузионном
;; переносе смеси в континуальном режиме.
;;
;; Вместе с уравнением Максвелла — Стефана
;; оно образует замкнутую систему для
;; распределений давления и состава смеси
;; при заданных молярных потоках.
;;
;; Полученные уравнения справедливы
;; в континуальном пределе. Для описания
;; переходного режима CPIM использует
;; интерполяцию с уравнениями
;; свободномолекулярного переноса.

;;
;; ### 2.3. Свободномолекулярный режим переноса
;;
;; Рассмотрим противоположный предел, когда длина
;; свободного пробега молекул значительно превышает
;; диаметр трубки:
;;
;; $$
;; Kn=\frac{\lambda}{d}\gg 1.
;; $$
;;
;; В этом режиме столкновения молекул со стенками
;; преобладают над межмолекулярными столкновениями.
;; Поэтому компоненты газовой смеси переносятся
;; практически независимо друг от друга.
;;
;; Перенос определяется тепловым движением молекул
;; и их взаимодействием со стенками трубки.
;;
;; #### 2.3.1. Кнудсеновский перенос
;;
;; Для длинной цилиндрической трубки кинетическая
;; теория газов связывает молярный поток компонента
;; с градиентом его молярной концентрации:
;;
;; $$
;; \boxed{
;; N_i=-D_{K,i}\frac{dc_i}{dz}.
;; }
;; $$
;;
;; Здесь $c_i$ — молярная концентрация компонента,
;; а $D_{K,i}$ — коэффициент кнудсеновского переноса.
;;
;; Важно, что $N_i$ представляет полный молярный
;; поток компонента, усреднённый по сечению трубки,
;; а не только его диффузионную составляющую.
;;
;; Коэффициент кнудсеновского переноса имеет вид
;;
;; $$
;; D_{K,i}=
;; \frac{2-f_i}{f_i}
;; \frac{d}{3}
;; \sqrt{\frac{8RT}{\pi M_i}},
;; $$
;;
;; где $f_i$ — коэффициент диффузного отражения
;; молекул компонента $i$ от стенки.
;;
;; В дальнейшем принимается полное диффузное
;; отражение для обоих компонентов:
;;
;; $$
;; f_1=f_2=1.
;; $$
;;
;; Тогда
;;
;; $$
;; \boxed{
;; D_{K,i}=
;; \frac{d}{3}\sqrt{\frac{8RT}{\pi M_i}}.
;; }
;; $$
;;
;; Таким образом, коэффициент кнудсеновского
;; переноса обратно пропорционален квадратному
;; корню из молярной массы компонента:
;;
;; $$
;; D_{K,i}\propto\frac{1}{\sqrt{M_i}}.
;; $$
;;
;; При одинаковой температуре и геометрии
;; лёгкие молекулы переносятся быстрее тяжёлых.
;;
;; #### 2.3.2. Уравнения для парциальных давлений
;;
;; В приближении идеального газа:
;;
;; $$
;; c_i=\frac{p_i}{RT}.
;; $$
;;
;; Поскольку температура трубки постоянна,
;; уравнение кнудсеновского переноса принимает вид
;;
;; $$
;; \boxed{
;; N_i=-\frac{D_{K,i}}{RT}
;; \frac{dp_i}{dz}.
;; }
;; $$
;;
;; Для рассматриваемой бинарной смеси:
;;
;; $$
;; \begin{aligned}
;; \frac{dp_1}{dz}
;; &=-\frac{RT}{D_{K,1}}N_1,\\[6pt]
;; \frac{dp_2}{dz}
;; &=-\frac{RT}{D_{K,2}}N_2.
;; \end{aligned}
;; $$
;;
;; Эти уравнения показывают, что в свободномолекулярном
;; пределе поток каждого компонента определяется
;; градиентом его собственного парциального давления.
;;
;; Межмолекулярное сопротивление переносу
;; в этом пределе отсутствует.
;;
;; #### 2.3.3. Уравнение полного давления
;;
;; Сложим уравнения для двух компонентов.
;;
;; Учитывая, что
;;
;; $$
;; p=p_1+p_2,
;; $$
;;
;; получаем
;;
;; $$
;; \boxed{
;; \frac{dp}{dz}
;; =-RT\left(
;; \frac{N_1}{D_{K,1}}+
;; \frac{N_2}{D_{K,2}}
;; \right).
;; }
;; $$
;;
;; Поскольку
;;
;; $$
;; D_{K,1}\sqrt{M_1}
;; =D_{K,2}\sqrt{M_2},
;; $$
;;
;; можно ввести общий коэффициент сопротивления
;; свободномолекулярному переносу:
;;
;; $$
;; A_K=
;; \frac{RT}{D_{K,i}\sqrt{M_i}}
;; =\frac{3}{d}\sqrt{\frac{\pi RT}{8}}.
;; $$
;;
;; Тогда уравнение градиента полного давления
;; записывается в виде
;;
;; $$
;; \boxed{
;; \frac{dp}{dz}
;; =-A_K\left(
;; \sqrt{M_1}N_1+\sqrt{M_2}N_2
;; \right).
;; }
;; $$
;;
;; По своей математической форме это уравнение
;; аналогично уравнению полного давления,
;; полученному для континуального режима.
;; Отличается только коэффициент сопротивления.
;;
;; #### 2.3.4. Уравнение изменения состава
;;
;; Для построения интерполяционной модели
;; необходимо также выразить градиент состава смеси.
;;
;; Используя соотношение
;;
;; $$
;; p_i=x_ip,
;; $$
;;
;; получаем
;;
;; $$
;; \frac{dp_i}{dz}
;; =p\frac{dx_i}{dz}
;; +x_i\frac{dp}{dz}.
;; $$
;;
;; Подставляя выражение для полного давления
;; в уравнение кнудсеновского переноса,
;; получаем для первого компонента:
;;
;; $$
;; \boxed{
;; c\frac{dx_1}{dz}
;; =
;; \frac{x_1N_2}{D_{K,2}}
;; -
;; \frac{x_2N_1}{D_{K,1}}.
;; }
;; $$
;;
;; Здесь
;;
;; $$
;; c=\frac{p}{RT},\qquad x_2=1-x_1.
;; $$
;;
;; Для второго компонента получается
;; аналогичное уравнение, но оно не является
;; независимым вследствие условия $x_1+x_2=1$.
;;
;; Таким образом, свободномолекулярный режим
;; описывается двумя уравнениями:
;;
;; $$
;; \boxed{
;; \begin{aligned}
;; c\frac{dx_1}{dz}
;; &=
;; \frac{x_1N_2}{D_{K,2}}
;; -
;; \frac{x_2N_1}{D_{K,1}},
;; \\[10pt]
;; \frac{dp}{dz}
;; &=-A_K
;; \left(\sqrt{M_1}N_1+\sqrt{M_2}N_2\right).
;; \end{aligned}
;; }
;; $$
;;
;; Эти уравнения имеют ту же структуру,
;; что и уравнения континуального режима.
;;
;; Именно это позволяет построить CPIM путём
;; интерполяции транспортных коэффициентов
;; между двумя предельными режимами.

;;
;; ### 2.4. Интерполяционная модель CPIM
;;
;; В континуальном и свободномолекулярном режимах
;; уравнения переноса имеют одинаковую математическую
;; структуру, но отличаются транспортными коэффициентами.
;;
;; Это позволяет построить интерполяционную модель,
;; применимую во всём диапазоне чисел Кнудсена.
;;
;; В CPIM отдельно интерполируются коэффициенты,
;; связывающие молярные потоки с градиентом состава,
;; и коэффициент, определяющий градиент полного давления.
;;
;; #### 2.4.1. Интерполяция переноса компонентов
;;
;; В континуальном режиме изменение состава
;; определяется уравнением Максвелла — Стефана:
;;
;; $$
;; c\frac{dx_1}{dz}
;; =\frac{x_1N_2-x_2N_1}{D_{12}}.
;; $$
;;
;; В свободномолекулярном режиме:
;;
;; $$
;; c\frac{dx_1}{dz}
;; =\frac{x_1N_2}{D_{K,2}}
;; -\frac{x_2N_1}{D_{K,1}}.
;; $$
;;
;; Введём интерполяционные коэффициенты
;; $\mathcal D_1$ и $\mathcal D_2$ по правилу
;; Бозанке:
;;
;; $$
;; \boxed{
;; \frac{1}{\mathcal D_i}
;; =\frac{1}{D_{12}}+\frac{1}{D_{K,i}},
;; \qquad i=1,2.
;; }
;; $$
;;
;; Эквивалентная запись:
;;
;; $$
;; \mathcal D_i=
;; \frac{D_{12}D_{K,i}}{D_{12}+D_{K,i}}.
;; $$
;;
;; Интерполяционное уравнение изменения состава
;; для нашей бинарной смеси принимает вид
;;
;; $$
;; \boxed{
;; c\frac{dx_1}{dz}
;; =\frac{x_1N_2}{\mathcal D_2}
;; -\frac{x_2N_1}{\mathcal D_1}.
;; }
;; $$
;;
;; Коэффициенты $\mathcal D_1$ и $\mathcal D_2$
;; в общем случае различаются, поскольку
;; молярные массы компонентов неодинаковы
;; и $D_{K,1}\ne D_{K,2}$.
;;
;; Проверим предельные случаи.
;;
;; При преобладании межмолекулярных столкновений
;; $D_{12}\ll D_{K,i}$, поэтому
;;
;; $$
;; \mathcal D_i\longrightarrow D_{12}.
;; $$
;;
;; Уравнение переходит в обычное уравнение
;; Максвелла — Стефана.
;;
;; При преобладании столкновений со стенками
;; $D_{12}\gg D_{K,i}$, поэтому
;;
;; $$
;; \mathcal D_i\longrightarrow D_{K,i}.
;; $$
;;
;; Получаем уравнение свободномолекулярного переноса.
;;
;; Таким образом, интерполяция воспроизводит
;; оба предельных режима.
;;
;; #### 2.4.2. Интерполяция градиента давления
;;
;; В обоих предельных режимах градиент полного
;; давления можно записать в одинаковой форме:
;;
;; $$
;; \frac{dp}{dz}
;; =-A\left(
;; \sqrt{M_1}N_1+\sqrt{M_2}N_2
;; \right).
;; $$
;;
;; В континуальном режиме коэффициент
;; сопротивления равен
;;
;; $$
;; A_C=
;; \frac{32\mu RT}{
;; pd^2\left(
;; x_1\sqrt{M_1}+x_2\sqrt{M_2}
;; \right)
;; }.
;; $$
;;
;; В свободномолекулярном режиме:
;;
;; $$
;; A_K=\frac{3}{d}\sqrt{\frac{\pi RT}{8}}.
;; $$
;;
;; Для промежуточного режима Young и Todd
;; предлагают интерполяционное соотношение
;;
;; $$
;; \boxed{
;; \frac{1}{A}
;; =\frac{1}{A_C}+\frac{1}{A_K}.
;; }
;; $$
;;
;; Или
;;
;; $$
;; A=\frac{A_CA_K}{A_C+A_K}.
;; $$
;;
;; При высоком давлении, когда преобладает
;; вязкий перенос, $A_C\ll A_K$ и
;;
;; $$
;; A\longrightarrow A_C.
;; $$
;;
;; При низком давлении, когда преобладает
;; свободномолекулярный перенос,
;; $A_K\ll A_C$ и
;;
;; $$
;; A\longrightarrow A_K.
;; $$
;;
;; В итоге для произвольного числа Кнудсена
;; получаем
;;
;; $$
;; \boxed{
;; \frac{dp}{dz}
;; =-A\left(
;; \sqrt{M_1}N_1+\sqrt{M_2}N_2
;; \right).
;; }
;; $$
;;
;; #### 2.4.3. Окончательная система CPIM
;;
;; Введём обозначения для правых частей
;; уравнений переноса:
;;
;; $$
;; \begin{aligned}
;; H&=
;; \frac{x_1N_2}{\mathcal D_2}
;; -\frac{x_2N_1}{\mathcal D_1},\\[8pt]
;; G&=
;; -A\left(
;; \sqrt{M_1}N_1+\sqrt{M_2}N_2
;; \right).
;; \end{aligned}
;; $$
;;
;; Здесь $G=dp/dz$, а $H=c\,dx_1/dz$.
;;
;; Уравнения CPIM принимают вид
;;
;; $$
;; \boxed{
;; \begin{aligned}
;; \frac{dx_1}{dz}&=\frac{RT}{p}H,\\[8pt]
;; \frac{dp}{dz}&=G.
;; \end{aligned}
;; }
;; $$
;;
;; Для численного решения удобно использовать
;; парциальные давления вместо полного давления
;; и мольной доли.
;;
;; Поскольку
;;
;; $$
;; p_1=x_1p,\qquad p_2=x_2p,
;; $$
;;
;; после дифференцирования получаем
;;
;; $$
;; \boxed{
;; \begin{aligned}
;; \frac{dp_1}{dz}&=x_1G+RT\,H,\\[8pt]
;; \frac{dp_2}{dz}&=x_2G-RT\,H.
;; \end{aligned}
;; }
;; $$
;;
;; Это окончательная система двух обыкновенных
;; дифференциальных уравнений первого порядка
;; для парциальных давлений компонентов смеси.
;;
;; При заданных молярных потоках $N_1$ и $N_2$
;; правые части определяются текущими значениями
;; $p_1$, $p_2$ и транспортными коэффициентами.
;;
;; В рассматриваемой задаче поток водорода $N_2$
;; задан регулятором, а поток сурьмы $N_1$
;; определяется из граничных условий.
;;
;; #### 2.4.4. Область применимости интерполяции
;;
;; Интерполяционные формулы CPIM воспроизводят
;; континуальный и свободномолекулярный пределы,
;; однако не являются точным решением кинетического
;; уравнения Больцмана.
;;
;; В переходном режиме они представляют собой
;; физически мотивированное приближение.
;;
;; Поэтому достоверность количественных результатов
;; должна оцениваться по предельным случаям,
;; сравнению с альтернативными моделями
;; и, при возможности, экспериментальным данным.

;;
;; ### 2.5. Численное решение краевой задачи
;;
;; Полученная система CPIM представляет собой
;; два обыкновенных дифференциальных уравнения
;; первого порядка для парциальных давлений
;; компонентов газовой смеси.
;;
;; Запишем её в векторной форме:
;;
;; $$
;; \frac{d\mathbf p}{dz}
;; =\mathbf f(\mathbf p,N_1,N_2),
;; \qquad
;; \mathbf p=
;; \begin{pmatrix}
;; p_1\\p_2
;; \end{pmatrix}.
;; $$
;;
;; Правая часть определяется уравнениями
;; предыдущего раздела:
;;
;; $$
;; \mathbf f=
;; \begin{pmatrix}
;; x_1G+RT\,H\\
;; x_2G-RT\,H
;; \end{pmatrix}.
;; $$
;;
;; Молярный поток водорода $N_2$ задан.
;; Молярный поток сурьмы $N_1$ неизвестен
;; и должен быть определён из граничных условий.
;;
;; #### 2.5.1. Метод пристрелки
;;
;; На выходе из трубки ($z=L$) известны оба
;; парциальных давления:
;;
;; $$
;; \begin{aligned}
;; p_1(L)&=0,\\
;; p_2(L)&=p_g+\frac{Q_2}{C_{\mathrm{trap}}}.
;; \end{aligned}
;; $$
;;
;; Поэтому при фиксированном пробном значении $N_1$
;; система представляет собой задачу Коши.
;;
;; Интегрирование выполняется от приёмной ампулы
;; к исходной, то есть от $z=L$ до $z=0$.
;; Направление численного интегрирования
;; противоположно положительному направлению
;; координаты $z$.
;;
;; В качестве численного метода может использоваться
;; метод Рунге — Кутты с контролем погрешности.
;;
;; В результате интегрирования получаем
;; распределения парциальных давлений
;; $p_1(z;N_1)$ и $p_2(z;N_1)$.
;;
;; При этом рассчитанное давление сурьмы
;; на входе в трубку должно удовлетворять
;; условию насыщения:
;;
;; $$
;; p_1(0;N_1)=p_{1,\mathrm{sat}}(T_s).
;; $$
;;
;; Введём функцию невязки:
;;
;; $$
;; \boxed{
;; F(N_1)=p_1(0;N_1)
;; -p_{1,\mathrm{sat}}(T_s).
;; }
;; $$
;;
;; Искомый молярный поток сурьмы определяется
;; как неотрицательный корень уравнения
;;
;; $$
;; \boxed{
;; F(N_1)=0,\qquad N_1⩾ 0.
;; }
;; $$
;;
;; Таким образом, исходная краевая задача
;; сводится к последовательному решению
;; задач Коши и поиску корня одного
;; скалярного нелинейного уравнения.
;;
;; #### 2.5.2. Подбор молярного потока сурьмы
;;
;; Для нахождения $N_1$ используется метод
;; поиска корня на интервале с противоположными
;; знаками невязки, например метод Брента.
;;
;; Нижняя граница интервала принимается равной нулю:
;;
;; $$
;; N_{1,\min}=0.
;; $$
;;
;; При этом из условия $p_1(L)=0$ следует
;; $p_1(z)=0$ во всей трубке, поэтому
;;
;; $$
;; F(0)=-p_{1,\mathrm{sat}}(T_s)<0.
;; $$
;;
;; Верхняя граница подбирается увеличением
;; пробного потока до получения
;; положительной невязки:
;;
;; $$
;; F(N_{1,\max})>0.
;; $$
;;
;; После нахождения интервала с изменением
;; знака невязки определяется корень.
;;
;; Если физически допустимый интервал
;; не удаётся найти, расчёт считается
;; незавершённым. В таком случае необходимо
;; проверить исходные параметры и условия
;; существования решения.
;;
;; #### 2.5.3. Контроль численного решения
;;
;; На всём интервале интегрирования должны
;; выполняться условия
;;
;; $$
;; \begin{aligned}
;; p_1(z)&⩾ 0,\\
;; p_2(z)&>0,\\
;; p(z)&=p_1(z)+p_2(z)>0.
;; \end{aligned}
;; $$
;;
;; Соответственно, мольные доли должны
;; удовлетворять условиям
;;
;; $$
;; 0⩽ x_i(z)⩽ 1,\qquad x_1+x_2=1.
;; $$
;;
;; Нарушение физических ограничений,
;; выход за допустимую область вычисления
;; транспортных коэффициентов или появление
;; нечисловых значений означает, что пробное
;; решение следует отклонить.
;;
;; Для найденного значения $N_1$ проверяется
;; выполнение граничного условия на входе:
;;
;; $$
;; |F(N_1)|⩽
;; \varepsilon_{\mathrm{abs}}
;; +\varepsilon_{\mathrm{rel}}
;; p_{1,\mathrm{sat}}(T_s).
;; $$
;;
;; Здесь $\varepsilon_{\mathrm{abs}}$
;; и $\varepsilon_{\mathrm{rel}}$ —
;; заданные абсолютный и относительный
;; допуски по давлению.
;;
;; Дополнительно проверяется численная сходимость:
;; при уменьшении шага интегрирования
;; рассчитанный поток сурьмы и распределения
;; парциальных давлений должны изменяться
;; в пределах установленной точности.
;;
;; #### 2.5.4. Расчёт расхода сурьмы
;;
;; После определения молярного потока $N_1$
;; молярный расход сурьмы через трубку равен
;;
;; $$
;; \boxed{
;; \overset{\cdot}{n}_1=N_1S.
;; }
;; $$
;;
;; Соответствующий массовый расход составляет
;;
;; $$
;; \boxed{
;; \overset{\cdot}{m}_1=M_1N_1S.
;; }
;; $$
;;
;; Одновременно решение позволяет определить
;; распределения полного давления и состава
;; газовой смеси вдоль трубки:
;;
;; $$
;; \begin{aligned}
;; p(z)&=p_1(z)+p_2(z),\\
;; x_1(z)&=\frac{p_1(z)}{p(z)},\\
;; x_2(z)&=\frac{p_2(z)}{p(z)}.
;; \end{aligned}
;; $$
;;
;; Таким образом, численная модель определяет
;; не только скорость переноса сурьмы,
;; но и распределения давлений и состава смеси,
;; необходимые для анализа режимов течения
;; внутри соединительной трубки.
;;
;;
;; ### 2.6. Транспортные коэффициенты
;;
;; Для численного решения уравнений CPIM необходимо
;; определить коэффициенты взаимной и кнудсеновской
;; диффузии, а также динамическую вязкость газовой смеси.
;;
;; Значения этих коэффициентов рассчитываются
;; по кинетической теории газов и полуэмпирическим
;; соотношениям. Они не являются самостоятельными
;; следствиями интерполяционной модели CPIM.
;;
;; #### 2.6.1. Коэффициенты кнудсеновского переноса
;;
;; При полном диффузном отражении молекул от стенок
;; длинной цилиндрической трубки коэффициент
;; кнудсеновского переноса компонента $i$ равен
;;
;; $$
;; \boxed{
;; D_{K,i}=
;; \frac{d}{3}
;; \sqrt{\frac{8RT}{\pi M_i}}.
;; }
;; $$
;;
;; Здесь $d$ — внутренний диаметр трубки,
;; $T$ — абсолютная температура газа,
;; $M_i$ — молярная масса компонента.
;;
;; Поскольку температура и диаметр трубки постоянны,
;; коэффициенты $D_{K,1}$ и $D_{K,2}$ не изменяются
;; по длине расчётной области.
;;
;; Отношение коэффициентов определяется только
;; молярными массами:
;;
;; $$
;; \frac{D_{K,2}}{D_{K,1}}
;; =\sqrt{\frac{M_1}{M_2}}.
;; $$
;;
;; Таким образом, кнудсеновский перенос водорода
;; значительно быстрее переноса молекул Sb₄.
;;
;; #### 2.6.2. Коэффициент взаимной диффузии
;;
;; Межмолекулярное сопротивление переносу описывается
;; коэффициентом взаимной диффузии $D_{12}$.
;;
;; Для его оценки используется первое приближение
;; Чепмена — Энскога в модели упругих столкновений
;; твёрдых сфер:
;;
;; $$
;; \boxed{
;; D_{12}=
;; \frac{3k_BT}{16p\sigma_{12}^{2}}
;; \sqrt{\frac{2k_BT}{\pi m_{\mathrm{red}}}}.
;; }
;; $$
;;
;; Здесь $k_B$ — постоянная Больцмана,
;; $\sigma_{12}$ — эффективный диаметр столкновения,
;; $m_{\mathrm{red}}$ — приведённая масса двух молекул.
;;
;; Эффективный диаметр столкновения определяется как
;;
;; $$
;; \sigma_{12}=\frac{\sigma_1+\sigma_2}{2},
;; $$
;;
;; а приведённая масса:
;;
;; $$
;; m_{\mathrm{red}}=
;; \frac{m_1m_2}{m_1+m_2},
;; \qquad
;; m_i=\frac{M_i}{N_{\mathrm{Av}}}.
;; $$
;;
;; В принятой модели коэффициент взаимной диффузии
;; обратно пропорционален полному давлению:
;;
;; $$
;; D_{12}\propto\frac{1}{p}.
;; $$
;;
;; Поскольку температура постоянна, произведение
;;
;; $$
;; \boxed{K_{12}=pD_{12}}
;; $$
;;
;; также постоянно по длине трубки.
;; Это позволяет вычислить $K_{12}$ один раз,
;; а локальный коэффициент взаимной диффузии
;; определять по выражению
;;
;; $$
;; D_{12}(z)=\frac{K_{12}}{p(z)}.
;; $$
;;
;; При уменьшении давления межмолекулярные
;; столкновения становятся менее частыми,
;; поэтому коэффициент взаимной диффузии возрастает.
;;
;; #### 2.6.3. Вязкости чистых компонентов
;;
;; Для паров сурьмы Sb₄ динамическая вязкость
;; оценивается в приближении твёрдых сфер:
;;
;; $$
;; \boxed{
;; \mu_1(T)=
;; \frac{5}{16\sigma_1^2}
;; \sqrt{\frac{m_1k_BT}{\pi}}.
;; }
;; $$
;;
;; Для молекулярного водорода используется
;; формула Сазерленда:
;;
;; $$
;; \boxed{
;; \mu_2(T)=\mu_{2,0}
;; \left(\frac{T}{T_{2,0}}\right)^{3/2}
;; \frac{T_{2,0}+S_2}{T+S_2}.
;; }
;; $$
;;
;; Здесь $\mu_{2,0}$ — вязкость водорода
;; при опорной температуре $T_{2,0}$,
;; а $S_2$ — постоянная Сазерленда.
;;
;; В изотермической модели обе индивидуальные
;; вязкости постоянны по длине трубки.
;;
;; #### 2.6.4. Динамическая вязкость смеси
;;
;; Вязкость бинарной смеси Sb₄–H₂ рассчитывается
;; по полуэмпирическому правилу Уилки:
;;
;; $$
;; \boxed{
;; \mu=
;; \sum_{i=1}^{2}
;; \frac{x_i\mu_i}
;; {\displaystyle\sum_{j=1}^{2}x_j\Phi_{ij}}.
;; }
;; $$
;;
;; Коэффициенты взаимодействия определяются
;; выражением
;;
;; $$
;; \Phi_{ij}=
;; \frac{
;; \left[
;; 1+\sqrt{\frac{\mu_i}{\mu_j}}
;; \left(\frac{M_j}{M_i}\right)^{1/4}
;; \right]^2
;; }{
;; \sqrt{8\left(1+\frac{M_i}{M_j}\right)}
;; }.
;; $$
;;
;; При этом $\Phi_{11}=\Phi_{22}=1$.
;;
;; В отличие от вязкостей чистых компонентов,
;; вязкость смеси изменяется по длине трубки,
;; поскольку зависит от локального состава:
;;
;; $$
;; \boxed{
;; \mu(z)=\mu\bigl(T,x_1(z),x_2(z)\bigr).
;; }
;; $$
;;
;; Поэтому при численном интегрировании
;; вязкость смеси должна пересчитываться
;; в каждой точке вместе с мольными долями.
;;
;; #### 2.6.5. Исходные параметры и неопределённости
;;
;; Для предварительного расчёта используются
;; следующие молярные массы компонентов:
;;
;; $$
;; \begin{aligned}
;; M_1&=0.48704\ \mathrm{kg/mol},\\
;; M_2&=0.00201588\ \mathrm{kg/mol}.
;; \end{aligned}
;; $$
;;
;; Эффективные диаметры молекул предварительно
;; принимаются равными
;;
;; $$
;; \begin{aligned}
;; \sigma_1&=0.600\ \mathrm{nm},\\
;; \sigma_2&=0.289\ \mathrm{nm}.
;; \end{aligned}
;; $$
;;
;; Для корреляции вязкости водорода используются
;; параметры
;;
;; $$
;; \begin{aligned}
;; \mu_{2,0}&=8.76\cdot10^{-6}\ \mathrm{Pa\,s},\\
;; T_{2,0}&=293.85\ \mathrm{K},\\
;; S_2&=72\ \mathrm{K}.
;; \end{aligned}
;; $$
;;
;; Эти параметры соответствуют исходным оценкам,
;; использованным в справочных расчётах проекта.
;;
;; Эффективный диаметр молекулы Sb₄ в данной модели
;; является оценочным параметром и требует
;; дополнительного обоснования.
;;
;; Модель твёрдых сфер не учитывает подробную
;; структуру межмолекулярных потенциалов,
;; а формула Сазерленда представляет собой
;; приближение температурной зависимости вязкости.
;;
;; Поэтому рассчитанный расход сурьмы следует
;; рассматривать с учётом неопределённости
;; транспортных коэффициентов.
;;
;; #### 2.6.6. Вычисление коэффициентов CPIM
;;
;; При заданной температуре и геометрии трубки
;; коэффициенты $D_{K,1}$, $D_{K,2}$ и $K_{12}$
;; вычисляются один раз.
;;
;; На каждом шаге интегрирования по текущим
;; значениям парциальных давлений определяются:
;;
;; $$
;; \begin{aligned}
;; p&=p_1+p_2,\\
;; x_1&=\frac{p_1}{p},\\
;; x_2&=\frac{p_2}{p},\\
;; D_{12}&=\frac{K_{12}}{p},\\
;; \mu&=\mu(T,x_1,x_2).
;; \end{aligned}
;; $$
;;
;; После этого вычисляются интерполяционные
;; коэффициенты $\mathcal D_1$, $\mathcal D_2$
;; и $A$, определённые в разделе 2.4.
;;
;; Таким образом, все коэффициенты правых частей
;; системы CPIM выражаются через известные
;; физические параметры и текущие значения
;; парциальных давлений.
;;
