(def ^:private reference
  ;; Generated by the independent report-based DOP853 and Brent calculation.
  (edn/read-string (slurp (io/resource "fixtures/cpim-reference.edn"))))

(defn- baseline []
  (solver/prepare-problem transport/default-parameters conditions))

(defn- near? [expected actual tolerance]
  (<= (abs (- expected actual)) tolerance))

(defn- ex-data-from [f]
  (try (f) nil (catch clojure.lang.ExceptionInfo ex (ex-data ex))))

(deftest flow-and-geometry-test
  (let [{:keys [diameter ref-pressure ref-volumetric-flow ref-temp]} conditions
        area (solver/cross-sectional-area diameter)
        throughput (solver/hydrogen-throughput ref-pressure ref-volumetric-flow)
        flow (solver/hydrogen-molar-flow transport/default-parameters throughput ref-temp)
        flux (solver/hydrogen-molar-flux flow diameter)]
    (is (near? (:area reference) area 2e-20))
    (is (near? (* 4 area) (solver/cross-sectional-area (* 2 diameter)) 1e-19))
    (is (near? (:throughput reference) throughput 1e-17))
    (is (near? (* 2 throughput)
               (solver/hydrogen-throughput ref-pressure (* 2 ref-volumetric-flow)) 1e-17))
    (is (near? (:hydrogen-flow reference) flow 1e-20))
    (is (near? (/ flow 2) (solver/hydrogen-molar-flow transport/default-parameters
                                              throughput (* 2 ref-temp)) 1e-20))
    (is (near? (:n2 reference) flux 1e-16))
    (is (near? (/ flux 4) (solver/hydrogen-molar-flux flow (* 2 diameter)) 1e-17)))
  (testing "A conductance in m^3/s converts throughput to a pressure drop in Pa"
    (is (== 3.0 (solver/trap-pressure-drop 0.006 0.002)))
    (is (== 1.5 (solver/trap-pressure-drop 0.006 0.004)))
    (is (== 7.0 (solver/outlet-hydrogen-pressure 4.0 3.0)))))

