(deftest full-solver-reference-test
  (let [problem (baseline)
        default-result (solver/solve problem)
        result (solver/solve problem {:ode-options profile-options :residual-tol 1e-8})
        expected-inlet (subvec (first (:profile reference)) 1 3)
        tolerance (:residual-tol solver/default-solver-options)]
    (is (= default-result (solver/solve problem)))
    (is (= :success (:status default-result)))
    (is (<= (abs (:residual default-result)) tolerance))
    (is (near? (:n1 reference) (:n1 default-result) 2e-6))
    (assert-profile-boundaries problem result)
    (is (<= (abs (:residual result)) 1e-8))
    (is (near? (:n1 reference) (:n1 result) 1e-9))
    (is (near? (:mass-flow reference) (:mass-flow result) 5e-14))
    (is (near? (:time reference) (solver/distillation-time 0.5 (:mass-flow result)) 0.005))
    (doseq [[expected actual] (map vector expected-inlet (:state result))]
      (is (near? expected actual 1e-6)))
    (is (near? (reduce + expected-inlet) (reduce + (:state result)) 1e-6))
    (is (= [(:n1 result) (:residual result)] ((juxt :x :fx) (:root-result result))))
    (assert-reference-profile (:profile reference) (:profile result))))

