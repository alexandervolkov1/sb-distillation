(defn- assert-profile-boundaries [problem {:keys [z state profile status]}]
  (is (= :success status))
  (is (= {:z (:length problem) :state (:outlet-state problem)} (first profile)))
  (is (= {:z 0.0 :state state} (peek profile)))
  (is (== z 0.0))
  (is (apply > (map :z profile)))
  (is (every? #(solver/valid-pressure-state? (:state %)) profile)))

(defn- interpolated-state [profile z]
  (let [[a b] (some (fn [[a b]] (when (>= (:z a) z (:z b)) [a b]))
                    (partition 2 1 profile))
        weight (/ (- z (:z a)) (- (:z b) (:z a)))]
    (mapv (fn [pa pb] (+ pa (* weight (- pb pa)))) (:state a) (:state b))))

(defn- assert-reference-profile [samples actual]
  ;; With the 0.001 m step cap, this allowance includes linear interpolation.
  (doseq [[z p1 p2 x1 x2] samples
          :let [[a b] (interpolated-state actual z)
                total (+ a b)]]
    (is (near? p1 a 0.002) (str "Sb4 at z=" z))
    (is (near? p2 b 0.002) (str "H2 at z=" z))
    (is (near? x1 (/ a total) 0.0003) (str "x1 at z=" z))
    (is (near? x2 (/ b total) 0.0003) (str "x2 at z=" z))))

(def ^:private profile-options
  {:abs-tol 1e-10 :rel-tol 1e-8 :initial-step 1e-8 :max-step 1e-3})

(deftest trial-integration-test
  (let [problem (baseline)]
    (doseq [{:keys [n1 profile outlet-derivatives]} (:trials reference)
            :let [trial (solver/evaluate-trial problem n1 profile-options)]]
      (testing (str "N1 = " n1)
        (assert-profile-boundaries problem trial)
        (is (= n1 (:n1 trial)))
        (is (= (:residual trial) (- (first (:state trial)) (:p1-in problem))))
        (is (near? (- (second (first profile)) (:saturation reference))
                   (:residual trial) 1e-5))
        (assert-reference-profile profile (:profile trial))
        (let [[a b] (:profile trial)
              dz (- (:z b) (:z a))]
          (doseq [[expected pa pb] (map vector outlet-derivatives (:state a) (:state b))]
            (is (near? expected (/ (- pb pa) dz) 0.01))))
        (when (zero? n1)
          (is (every? #(zero? (first (:state %))) (:profile trial))))))
    (is (not (contains? (solver/integrate-trial problem 0.0) :residual)))
    (doseq [n1 [-1.0 ##NaN ##Inf ##-Inf "0" nil -1e-500M 1e-500M]]
      (is (= {:n1 n1} (ex-data-from #(solver/integrate-trial problem n1)))))))

(deftest integration-failure-preserves-diagnostics-test
  (let [problem (baseline)
        failed (solver/evaluate-trial problem (:n1 reference) {:max-attempts 1})]
    (is (= [:failed :max-attempts 1] ((juxt :status :reason :attempts) failed)))
    (is (pos? (:z failed)))
    (is (= (:state failed) (:state (peek (:profile failed)))))
    (is (= (:outlet-state problem) (:state (first (:profile failed)))))
    (is (not (contains? failed :residual)))
    (testing "Neither a trial nor solve allows ODE options to override the physical predicate"
      (with-redefs [model/pressure-derivatives (constantly [1.0 0.0])]
        (let [opts {:valid-state? (constantly true) :initial-step 0.01 :min-step 0.01}
              trial (solver/evaluate-trial problem 0.0 opts)
              result (solver/solve problem {:ode-options opts})]
          (is (= [:failed :step-too-small] ((juxt :status :reason) trial)))
          (is (= :invalid-state (get-in trial [:last-rejection :reason])))
          (is (= [{:z 0.5 :state (:outlet-state problem)}] (:profile trial)))
          (is (not (contains? trial :residual)))
          (is (= [:failed :bracketing :integration-failed]
                 ((juxt :status :stage :reason) result)))
          (is (= trial (:trial result)))
          (is (not (contains? result :mass-flow))))))))

(defn- trial-evaluator [evaluations residual]
  (fn [_pressure-derivatives _problem n1 options]
    (swap! evaluations conj [n1 options])
    (let [value (residual n1)]
      (merge {:n1 n1 :profile [{:z 0.0 :state [n1 1.0]}]}
             (if (map? value) value {:status :success :residual value})))))

(deftest bracket-search-test
  (is (near? (:molecular-flux reference) (solver/molecular-flux-estimate (baseline)) 1e-16))
  (let [result (solver/find-shooting-bracket (baseline))]
    (is (= :success (:status result)))
    (is (neg? (get-in result [:lower-trial :residual])))
    (is (pos? (get-in result [:upper-trial :residual])))
    (is (apply < (first (:bracket result)) [(:n1 reference) (second (:bracket result))])))
  (let [calls (atom [])
        opts {:max-attempts 20}]
    (with-redefs [shared-solver/molecular-flux-estimate (constantly 1.0)
                  shared-solver/evaluate-trial (trial-evaluator calls #(- % 4.0))]
      (let [result (solver/find-shooting-bracket {} opts 4)]
        (is (= (mapv #(vector % opts) [0.0 1.0 2.0 4.0]) @calls))
        (is (= [:success [2.0 4.0] 4] ((juxt :status :bracket :trials) result)))
        (is (= -2.0 (get-in result [:lower-trial :residual])))
        (is (= 0.0 (get-in result [:upper-trial :residual]))))
      (reset! calls [])
      (let [result (solver/find-shooting-bracket {} opts 3)]
        (is (= [0.0 1.0 2.0] (mapv first @calls)))
        (is (= [:failed :max-trials 3] ((juxt :status :reason :trials) result)))
        (is (= 2.0 (get-in result [:lower-trial :n1]))))))
  (doseq [limit [1 0 2.5 nil]]
    (is (= {:max-trials limit}
           (ex-data-from #(solver/find-shooting-bracket (baseline) {} limit))))))

